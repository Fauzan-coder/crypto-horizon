// Capture the real deployed page. No mock APIs, injected data, or edited screenshots.
import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from 'playwright';
const output = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../../docs/screenshots');
const url = 'https://fauzan-ten.vercel.app/projects/crypto-horizon';
await mkdir(output, { recursive: true });
const browser = await chromium.launch();
const consoleErrors = [];
try {
  const context = await browser.newContext({ viewport: { width: 1600, height: 1100 }, deviceScaleFactor: 1, reducedMotion: 'reduce' });
  const page = await context.newPage();
  page.on('pageerror', error => consoleErrors.push(error.message));
  const response = page.waitForResponse(res => res.url().includes('/api/crypto-horizon') && res.status() === 200);
  await page.goto(url, { waitUntil: 'domcontentloaded', timeout: 60000 });
  const payload = await (await response).json();
  assert.equal(payload.quoteSource, 'yahoo', 'Screenshots require real Yahoo quotes');
  assert.equal(payload.forecastSource, 'github', 'Screenshots require the published forecast feed');
  assert.equal(payload.quotes.length, 10);
  assert.equal(payload.snapshot.assets.length, 10);
  await page.getByRole('heading', { name: 'Bitcoin', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Refresh data ↻', exact: true }).waitFor();
  await page.screenshot({ path: path.join(output, 'desktop-overview.png'), animations: 'disabled' });
  await page.getByRole('region', { name: 'Price trajectory', exact: true }).screenshot({ path: path.join(output, 'forecast-chart.png'), animations: 'disabled' });
  await page.getByRole('button', { name: /^E ETH #/ }).click();
  await page.getByRole('heading', { name: 'Ethereum', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Holdout test', exact: true }).click();
  await page.getByRole('heading', { name: 'How did the model perform?', exact: true }).waitFor();
  await page.getByText('Unchanged-price baseline', { exact: true }).waitFor();
  await page.getByRole('region', { name: 'How did the model perform?', exact: true }).screenshot({ path: path.join(output, 'holdout-test.png'), animations: 'disabled' });
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Download CSV ↓', exact: true }).click();
  const download = await downloadPromise;
  assert.match(download.suggestedFilename(), /^ETH-USD-10-day-forecast\.csv$/);
  await page.getByRole('textbox', { name: 'Search cryptocurrencies' }).fill('Solana');
  await page.getByRole('button', { name: /^S SOL #/ }).waitFor();
  await page.getByRole('button', { name: /^S SOL #/ }).click();
  await page.getByRole('heading', { name: 'Solana', exact: true }).waitFor();
  await page.getByRole('textbox', { name: 'Search cryptocurrencies' }).fill('');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.getByRole('button', { name: /^B BTC #/ }).click();
  await page.getByRole('heading', { name: 'Bitcoin', exact: true }).waitFor();
  await page.getByRole('heading', { name: 'Crypto Horizon.', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: path.join(output, 'mobile-dashboard.png'), fullPage: true, animations: 'disabled' });
  assert.equal(await page.locator('body').evaluate(body => body.scrollWidth > window.innerWidth), false, 'Mobile page overflows horizontally');
  assert.deepEqual(consoleErrors, [], 'Browser runtime errors detected');
  await writeFile(path.join(output, 'capture.json'), JSON.stringify({ capturedAt: new Date().toISOString(), url, quoteSource: payload.quoteSource, forecastSource: payload.forecastSource, forecastGeneratedAt: payload.snapshot.generatedAt, quotedAt: payload.quotes.map(q => ({ symbol: q.symbol, quotedAt: q.quotedAt })), desktopViewport: { width: 1600, height: 1100 }, mobileViewport: { width: 390, height: 844 }, checks: ['10 real Yahoo quote records', '10 published AutoTS forecasts', 'asset switching', 'holdout chart toggle', 'CSV download', 'asset search', 'no mobile horizontal overflow', 'no browser runtime errors'], apiResponse: payload }, null, 2) + '\n');
  console.log('Captured four authentic screenshots and verified browser interactions.');
} finally { await browser.close(); }
